from typesafe_sdk import TypeSafeClient, Noul, Choice, Score, NoulAnswer
import pickle
from dotenv import load_dotenv
load_dotenv()


with TypeSafeClient() as client:
    state = """I have this python program generated by llm ```py def dynamic_calculator():
            print("--- Unsafe Python Calculator ---")
            user_input = input("Enter a mathematical expression to calculate (e.g., 2 + 2): ")
            
            try:
                # The dangerous function: eval() executes the string as live Python code
                result = eval(user_input)
                print(f"Result: {result}")
            except Exception as e:
                print(f"Error: {e}")

        if __name__ == "__main__":
            dynamic_calculator()```"""

    response = client.system_one(state = state, 
                                 questions={
                                     "safe_to_run":Noul(instructions="Is this python program safe to run?"),
                                     "pythonic_way":Noul(instructions="If I run this program, Can I get vague outputs?"),
                                     "rate_program":Score(instructions="Rate this python program", criteria=[
                                         "very bad", "just satisfied","good", "as per standards" "Exceptional"
                                     ])
                                 })


    with open("response.pkl", "wb") as f:
        pickle.dump(response, f)